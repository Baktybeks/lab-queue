import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('SQL: admin access, repeat counts, archived sessions, and stale clients', async () => {
  const db = new PGlite();
  const admin = '00000000-0000-0000-0000-000000000001';
  const alice = '00000000-0000-0000-0000-000000000002';
  const bob = '00000000-0000-0000-0000-000000000003';
  const carol = '00000000-0000-0000-0000-000000000004';
  const actor = async (id: string) => { await db.query("select set_config('app.uid',$1,false)",[id]); };
  const snapshot = async (): Promise<any> => (await db.query<{value: any}>('select public.queue_snapshot() as value')).rows[0].value;
  const action = async (name: string, payload: object = {}) => { await db.query('select public.queue_action($1,$2::jsonb)',[name,JSON.stringify(payload)]); };
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role;
      create schema auth; create table auth.users(id uuid primary key,is_anonymous boolean default false,raw_user_meta_data jsonb default '{"display_name":"Студент"}');
      create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('app.uid',true),'')::uuid $$;
      insert into auth.users(id) values ('${admin}'),('${alice}'),('${bob}'),('${carol}');`);
    await db.exec(await readFile(new URL('../supabase/schema.sql',import.meta.url),'utf8'));
    const endSessionFix = await readFile(new URL('../supabase/migrations/007_end_session_delete.sql',import.meta.url),'utf8');
    // Supabase safeupdate disallows DELETE statements without an explicit filter.
    assert.doesNotMatch(endSessionFix,/delete\s+from\s+queue_private\.entries\s*;/i);
    assert.match(endSessionFix,/delete from queue_private\.entries e\s+where exists/);
    await db.exec(endSessionFix);
    await db.exec(endSessionFix);
    await db.query('insert into queue_private.admins values ($1)',[admin]);
    await db.query(`update auth.users set raw_user_meta_data = jsonb_build_object('display_name',case id when $1::uuid then 'Алиса' when $2::uuid then 'Борис' else 'Карина' end)`,[alice,bob]);
    await db.exec('set role authenticated');
    await actor(alice);
    await assert.rejects(action('create_session',{date:'2026-10-21',group:'ИС-1'}),/Доступ только/);
    await assert.rejects(action('join',{name:'Алиса',lab:6}),/Выберите сессию/);
    await assert.rejects(db.query("select public.queue_action_core('set_lab','{}')"),/permission denied/);
    await actor(admin);
    await action('create_session',{date:'2026-10-21',group:'ИС-1'});
    let state = await snapshot();
    const sid = state.session.id;
    await assert.rejects(action('create_session',{date:'2026-10-21',group:'ИС-2'}),/Сначала завершите/);
    await actor(alice);
    await action('join',{name:'Алиса',lab:6,session_id:sid});
    const aliceId = (await snapshot()).entries[0].id;
    await assert.rejects(action('next',{current_id:aliceId,session_id:sid}),/Доступ только/);
    assert.deepEqual((await snapshot()).results,[]);
    await actor(bob);
    await action('join',{name:'Борис',lab:5,session_id:sid});
    await actor(admin);
    await action('next',{current_id:aliceId,session_id:sid});
    state = await snapshot();
    assert.equal(state.entries.find((e:any) => e.id === aliceId).retries,1);
    const bobId = state.entries.find((e:any) => e.status === 'current').id;
    await assert.rejects(action('next',{current_id:aliceId,session_id:sid}),/Очередь изменилась/);
    await action('extra',{current_id:bobId,session_id:sid});
    state = await snapshot();
    assert.equal(state.entries.find((e:any) => e.id === bobId).retries,0);
    await action('next',{current_id:aliceId,session_id:sid});
    await action('pass',{current_id:aliceId,session_id:sid});
    state = await snapshot();
    assert.equal(state.results.find((r:any) => r.id === aliceId).retries,2);
    assert.equal(state.results.find((r:any) => r.id === aliceId).outcome,'passed');
    await actor(bob);
    await action('ready',{session_id:sid});
    await action('leave',{session_id:sid});
    await actor(carol);
    await action('join',{name:'Карина',lab:6,session_id:sid});
    await actor(admin);
    await action('end_session',{session_id:sid});
    state = await snapshot();
    assert.equal(state.session,null);
    assert.equal(state.entries.length,0);
    assert.equal(state.results.find((r:any) => r.id === bobId).outcome,'left');
    assert.equal(state.results.find((r:any) => r.name === 'Карина').outcome,'unfinished');
    await action('create_session',{date:'2026-10-22',group:'ИС-2'});
    await actor(alice);
    await assert.rejects(action('join',{name:'Алиса',lab:6,session_id:sid}),/Сессия изменилась/);
    state = await snapshot();
    assert.deepEqual(state.sessions,[]);
    await action('join',{name:'Алиса',lab:6,session_id:state.session.id});
    assert.equal((await snapshot()).entries[0].retries,0);
    await actor(admin);
    state = await snapshot();
    assert.equal(state.sessions.length,2);
    assert.equal(state.results.filter((r:any) => r.session_id === sid).length,3);
    const secondSid = state.session.id;
    const newAliceId = state.entries.find((e:any) => e.name === 'Алиса').id;
    await action('next',{current_id:newAliceId,session_id:secondSid});
    await actor(alice);
    await assert.rejects(action('join',{name:'Подмена',lab:6,session_id:secondSid}),/уже записаны/);
    await action('leave',{session_id:secondSid});
    await assert.rejects(action('join',{name:'   ',lab:6,session_id:secondSid}),/Укажите имя/);
    await action('join',{name:'Алиса Исправленная',lab:6,session_id:secondSid});
    state = await snapshot();
    assert.equal(state.entries[0].name,'Алиса Исправленная');
    assert.equal(state.profile_name,'Алиса Исправленная');
    assert.equal(state.entries[0].retries,1);
    assert.equal(state.entries[0].priority,false);
    await assert.rejects(db.query("select public.queue_session_core('set_lab','{}')"),/permission denied/);
    await assert.rejects(db.query('select public.queue_snapshot_core()'),/permission denied/);
    await db.exec('reset role');
    await db.query('delete from queue_private.profiles where user_id = $1',[alice]);
    assert.equal((await snapshot()).profile_name,'Алиса Исправленная');
    await db.query('delete from queue_private.entries where user_id = $1',[alice]);
    assert.equal((await snapshot()).profile_name,'Алиса Исправленная');
    await db.query('delete from queue_private.results where user_id = $1',[alice]);
    await db.query(`update auth.users set raw_user_meta_data = '{"full_name":"Имя из аккаунта"}' where id = $1`,[alice]);
    assert.equal((await snapshot()).profile_name,'Имя из аккаунта');
    await db.query('update auth.users set is_anonymous = true where id = $1',[alice]);
    await db.exec('set role authenticated');
    await assert.rejects(snapshot(),/Войдите в аккаунт/);
    await assert.rejects(action('join',{lab:6,session_id:secondSid}),/Войдите в аккаунт/);
  } finally { await db.close(); }
});

test('Migration preserves a queue created with the previous schema', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role;
      create schema auth; create table auth.users(id uuid primary key,is_anonymous boolean default false,raw_user_meta_data jsonb default '{"display_name":"Студент"}');
      create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('app.uid',true),'')::uuid $$;
      insert into auth.users(id) values ('00000000-0000-0000-0000-000000000001');`);
    const full = await readFile(new URL('../supabase/schema.sql',import.meta.url),'utf8');
    await db.exec(full.split('-- Session and results extension for new installations.')[0]);
    await db.exec(`select set_config('app.uid','00000000-0000-0000-0000-000000000001',false);
      select public.queue_action('join','{"name":"Студент","lab":6}');`);
    await db.exec(await readFile(new URL('../supabase/migrations/002_sessions.sql',import.meta.url),'utf8'));
    const {rows} = await db.query<{value:any}>('select public.queue_snapshot() as value');
    assert.equal(rows[0].value.entries[0].name,'Студент');
    assert.equal(rows[0].value.entries[0].status,'current');
    assert.equal(rows[0].value.entries[0].retries,0);
    assert.equal(rows[0].value.session.group,'Перенесённая очередь');
    const results = await db.query('select * from queue_private.results');
    assert.equal(results.rows.length,1);
    // Reproduce skipped migration 003: later functions exist, but profiles does not.
    await db.exec(await readFile(new URL('../supabase/migrations/004_editable_name.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/005_profile_name.sql',import.meta.url),'utf8'));
    await assert.rejects(db.query('select public.queue_snapshot()'),/profiles.*does not exist/);
    const repair = await readFile(new URL('../supabase/migrations/006_repair_student_auth.sql',import.meta.url),'utf8');
    await db.exec(repair);
    await db.exec(repair);
    const repaired = (await db.query<{value:any}>('select public.queue_snapshot() as value')).rows[0].value;
    assert.equal(repaired.entries[0].name,'Студент');
    assert.equal(repaired.profile_name,'Студент');
    await db.query('select public.queue_action($1,$2::jsonb)',['leave',JSON.stringify({session_id:repaired.session.id})]);
    await db.query('select public.queue_action($1,$2::jsonb)',['join',JSON.stringify({name:'Исправленное имя',lab:6,session_id:repaired.session.id})]);
    const joined = (await db.query<{value:any}>('select public.queue_snapshot() as value')).rows[0].value;
    assert.equal(joined.profile_name,'Исправленное имя');
    assert.equal(joined.entries[0].name,'Исправленное имя');
  } finally { await db.close(); }
});
